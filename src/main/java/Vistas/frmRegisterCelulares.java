    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String searchCliente = txtSearch.getText().trim();

        taCelulares.setText("");
        boolean enc = false;

        for (Celular c : listaCelulares) {
            if (c.getMarca().trim().equalsIgnoreCase(searchCliente)) {
                taCelulares.append(c.toString() + "\n\n");
                enc = true;
            }
        }
        if (!enc) {
            JOptionPane.showMessageDialog(this, "No se encontro ningun celular");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

