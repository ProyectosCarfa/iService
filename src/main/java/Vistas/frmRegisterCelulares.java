    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String celulareliminado = JOptionPane.showInputDialog("Ingrese el ID del celular eliminado.").trim();
        byte id = Byte.parseByte(celulareliminado);
        boolean eliminado = false;

        for (int i = 0; i < listaCelulares.size(); i++) {
            if (listaCelulares.get(i).getId() == id) {
                listaCelulares.remove(i);
                eliminado = true;
                break;
            }
        }
        if (eliminado) {
            JOptionPane.showMessageDialog(this, "CELULAR ELIMINADO CON EXITO");
            taCelulares.setText("");
            for (Celular ce : listaCelulares) {
                taCelulares.append(ce.toString() + "\n");
            }
        } else {
            JOptionPane.showMessageDialog(this, "NO SE ENCONTRO ID");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

