    private void txtClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtClienteActionPerformed
        String buscarcliente = txtCliente.getText();

        byte idBuscado = Byte.parseByte(buscarcliente);

        Clientes clienteEncontrado = new Clientes();
        for (Clientes c : listaClientes) {
            if (c.getId() == idBuscado) {
                clienteEncontrado = c;
                break;
            }
        }

        if (clienteEncontrado != null) {
            JOptionPane.showMessageDialog(this, "Cliente encontrado ✅\n" + "Nombre: " + clienteEncontrado.getNombre());
        } else {
            JOptionPane.showMessageDialog(this, "Cliente no existe ❌");
            txtCliente.setText("");
        }

    }//GEN-LAST:event_txtClienteActionPerformed

